"""Генератор xlsx для онбординга Print Cafe.

После работы агента-аналитика этот файл генерирует не «пустые шаблоны»,
а **частично заполненные** прайсы — по данным с сайта printcafe34.ru.

Логика заполнения:
- Где данные взяты с сайта — они проставлены явно.
- Где данных на сайте нет — стоит строка `(?)` или `[TODO заказчик]`.
- Заказчик правит руками только то, что помечено `(?)` / `[TODO]`.
- Источник каждого факта — в `_extracted_from_site.md`.

Запуск:
    uv run python client_intake/_generate_xlsx.py
или
    python client_intake/_generate_xlsx.py

Создаёт:
    - 02_products.xlsx
    - 03_pricing.xlsx
"""

from __future__ import annotations

from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

HERE = Path(__file__).parent

HEADER_FILL = PatternFill("solid", fgColor="1F4E78")
HEADER_FONT = Font(bold=True, color="FFFFFF", size=11)
DATA_FILL = PatternFill("solid", fgColor="FFFFFF")
DATA_FONT = Font(color="111111")
TODO_FILL = PatternFill("solid", fgColor="FFF6D6")
TODO_FONT = Font(italic=True, color="8A6D00")
WRAP = Alignment(wrap_text=True, vertical="top")
HEADER_ALIGN = Alignment(wrap_text=True, vertical="center", horizontal="center")

TODO_MARK = "(?)"
TODO_LONG = "[TODO заказчик]"


def style_header(ws: Worksheet, columns: list[tuple[str, int]]) -> None:
    """Шапка: жирный белый текст на синем фоне, заморозка первой строки."""
    for col_idx, (title, width) in enumerate(columns, start=1):
        cell = ws.cell(row=1, column=col_idx, value=title)
        cell.font = HEADER_FONT
        cell.fill = HEADER_FILL
        cell.alignment = HEADER_ALIGN
        ws.column_dimensions[get_column_letter(col_idx)].width = width
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "A2"


def fill_rows(ws: Worksheet, rows: list[list[object]]) -> None:
    """Заполнить данные. Ячейки с TODO_MARK / TODO_LONG подсвечиваются жёлтым."""
    for row_idx, row in enumerate(rows, start=2):
        for col_idx, value in enumerate(row, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.alignment = WRAP
            text = str(value) if value is not None else ""
            if TODO_MARK in text or TODO_LONG in text:
                cell.fill = TODO_FILL
                cell.font = TODO_FONT
            else:
                cell.fill = DATA_FILL
                cell.font = DATA_FONT
        ws.row_dimensions[row_idx].height = 48


